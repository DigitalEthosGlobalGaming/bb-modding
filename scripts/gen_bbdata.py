#!/usr/bin/env python3
"""Generate examples/inspector/src/bbdata.rs from an Openborne/data checkout.

    python3 scripts/gen_bbdata.py /path/to/Openborne-data > examples/inspector/src/bbdata.rs

For every param: field layout from paramdef/*.txt (offsets computed here, with
bitfield and array packing), the row size measured from param/*.txt (gap
between consecutive rows' data offsets), and whether the two agree. Every
layout is emitted with its computed size; the browser uses a layout only when
that size equals the row stride it measures in memory (and dump_verified
records whether Openborne's dump agreed too). English item, weapon
and armor names come from fmg/engus/item.
"""
import os, re, sys

SIZES = {'s8': 1, 'u8': 1, 'dummy8': 1, 's16': 2, 'u16': 2, 's32': 4, 'u32': 4, 'f32': 4}
RUST_TY = {'s8': 'S8', 'u8': 'U8', 'dummy8': 'U8', 's16': 'S16', 'u16': 'U16', 's32': 'S32', 'u32': 'U32', 'f32': 'F32'}

def rows(path):
    with open(path, encoding='utf-8', errors='replace') as f:
        return [l.rstrip('\n').split('\t') for l in f]

def layout(defpath):
    """[(name, ty, off, bit, nbits)], total size, st name."""
    lines = rows(defpath)
    head = lines[0]
    ci = {k: i for i, k in enumerate(head)}
    out, off, st = [], 0, None
    unit_off = unit_ty = None; unit_used = 0
    for r in lines[1:]:
        if len(r) < len(head) - 4: continue
        st = st or r[ci['paramDef']]
        ty, var = r[ci['type']].strip(), r[ci['varname']].strip()
        if ty not in SIZES: return None, 0, st
        size = SIZES[ty]
        m = re.match(r'^(\w+):(\d+)$', var)
        if m:  # bitfield packed into a unit of the base type
            name, nb = m.group(1), int(m.group(2))
            pack_ty = 'u8' if ty == 'dummy8' else ty  # dummy8 padding bits share the u8 unit
            if unit_ty != pack_ty or unit_used + nb > size * 8:
                unit_off, unit_ty, unit_used = off, pack_ty, 0
                off += size
            out.append((name, ty, unit_off, unit_used, nb))
            unit_used += nb
            continue
        unit_ty = None
        m = re.match(r'^(\w+)\[(\d+)\]$', var)
        if m:  # array: only padding arrays in practice; keep as one blob
            name, n = m.group(1), int(m.group(2))
            if not name.startswith('pad') and not name.startswith('dummy'):
                for k in range(n):
                    out.append((f'{name}[{k}]', ty, off + k * size, 0, 0))
            off += size * n
            continue
        out.append((var, ty, off, 0, 0))
        off += size
    return out, off, st

def measured_row_size(parampath):
    lines = rows(parampath)
    addrs = []
    for r in lines:
        if len(r) > 2 and r[0].startswith('0x') and r[1].startswith('0x'):
            try: addrs.append(int(r[1], 16))
            except ValueError: pass
    gaps = sorted({b - a for a, b in zip(addrs, addrs[1:]) if b > a})
    return gaps[0] if gaps else 0

def names(path):
    out = []
    if not os.path.exists(path): return out
    for r in rows(path):
        if len(r) >= 2 and r[0].strip().lstrip('-').isdigit() and r[1].strip() and r[1].strip() != '*':
            out.append((int(r[0]), r[1].strip()))
    return sorted(set(out))

def rs(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

def main(root):
    print('// @generated by scripts/gen_bbdata.py from Openborne/data. Do not edit.')
    print('// Param layouts (Bloodborne PS4, 64-bit params) and English item names.')
    print('#![allow(dead_code)]')
    print('use crate::params::{Field, ParamDef, Ty};\n')
    defs = []
    for fn in sorted(os.listdir(os.path.join(root, 'paramdef'))):
        stem = fn[:-4]
        fields, total, st = layout(os.path.join(root, 'paramdef', fn))
        pp = os.path.join(root, 'param', fn)
        measured = measured_row_size(pp) if os.path.exists(pp) else 0
        if not st: continue
        ok = fields is not None and measured and total == measured
        defs.append((stem, st, fields or [], total, measured, ok))
    for stem, st, fields, total, measured, ok in defs:
        print(f'static F_{stem.upper()}: &[Field] = &[')
        for (n, ty, off, bit, nb) in fields:
            print(f'    Field {{ name: {rs(n)}, ty: Ty::{RUST_TY[ty]}, off: {off}, bit: {bit}, bits: {nb} }},')
        print('];')
    print('\npub static PARAMS: &[ParamDef] = &[')
    for stem, st, fields, total, measured, ok in defs:
        print(f'    ParamDef {{ file: {rs(stem)}, st: {rs(st)}, layout_size: {total if fields else 0}, dump_row_size: {measured}, dump_verified: {"true" if ok else "false"}, fields: F_{stem.upper()} }},')
    print('];')
    for var, fn in (('GOODS_NAMES', 'アイテム名.txt'), ('WEAPON_NAMES', '武器名.txt'), ('ARMOR_NAMES', '防具名.txt')):
        lst = names(os.path.join(root, 'fmg', 'engus', 'item', fn))
        print(f'\n/// (id, English name), sorted by id.\npub static {var}: &[(i32, &str)] = &[')
        for i, n in lst: print(f'    ({i}, {rs(n)}),')
        print('];')
    v = sum(1 for d in defs if d[5])
    sys.stderr.write(f'{len(defs)} params, {v} layouts verified against measured row size\n')
    for stem, st, fields, total, measured, ok in defs:
        if not ok: sys.stderr.write(f'  unverified: {stem} computed {total} measured {measured}\n')

main(sys.argv[1])
